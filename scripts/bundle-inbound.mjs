// Bundles the shared domain code for the `inbound` Edge Function (Deno can't load the app's
// extensionless imports). Run after changing src/domain or src/db/rows.ts; inbound.test.ts checks
// the bundle is current and that it only contains pure code.
import { rolldown } from "rolldown";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

export const OUT = "supabase/functions/inbound/core.bundle.js";

/** The bundle's code and the files that went into it (forward slashes). */
export async function bundle() {
  const b = await rolldown({ input: "supabase/functions/inbound/core.ts", platform: "neutral", resolve: { mainFields: ["module", "main"] }, logLevel: "warn" });
  const { output } = await b.generate({ format: "esm" });
  const inputs = Object.keys(output[0].modules).map((m) => m.replace(/\\/g, "/"));
  return { code: `// Generated by scripts/bundle-inbound.mjs from core.ts. Do not edit.\n${output[0].code}`, inputs };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { code } = await bundle();
  writeFileSync(OUT, code);
  console.log(`wrote ${OUT} (${(code.length / 1024).toFixed(0)} KB)`);
}
