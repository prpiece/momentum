// Bundles the shared domain code for the Edge Functions (Deno can't load the app's extensionless
// imports): `inbound` (D304) and `calendar` (D345). Run after changing src/domain or src/db/rows.ts;
// inbound.test.ts and calendarBundle.test.ts check the bundles are current and only contain pure code.
import { rolldown } from "rolldown";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

export const FUNCTIONS = ["inbound", "calendar"];
export const outOf = (fn) => `supabase/functions/${fn}/core.bundle.js`;
export const OUT = outOf("inbound");

/** A function's bundle code and the files that went into it (forward slashes). */
export async function bundle(fn = "inbound") {
  const b = await rolldown({ input: `supabase/functions/${fn}/core.ts`, platform: "neutral", resolve: { mainFields: ["module", "main"] }, logLevel: "warn" });
  const { output } = await b.generate({ format: "esm" });
  const inputs = Object.keys(output[0].modules).map((m) => m.replace(/\\/g, "/"));
  return { code: `// Generated by scripts/bundle-inbound.mjs from core.ts. Do not edit.\n${output[0].code}`, inputs };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  for (const fn of FUNCTIONS) {
    const { code } = await bundle(fn);
    writeFileSync(outOf(fn), code);
    console.log(`wrote ${outOf(fn)} (${(code.length / 1024).toFixed(0)} KB)`);
  }
}
